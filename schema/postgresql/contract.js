'use strict';

const { createHash } = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');

const migrations = ['001_baseline.sql','account_weights.sql','account.sql','timestamps.sql','private_text.sql'];

// 统一换行后计算迁移摘要，避免 Windows 检出改变基线身份。
function source(file) {
    return fs.readFileSync(path.join(__dirname,file),'utf8').replace(/\r\n/g,'\n');
}

// 计算一份发布件中单个 SQL 文件的内容身份。
function digest(text) { return createHash('sha256').update(text).digest('hex'); }

// 生成 Node 和 C++ 同时使用的版本摘要及结构查询。
function describe() {
    const files = [...migrations,'fingerprint.sql'];
    // 按发布清单顺序计算内容摘要。
    const hashes = Object.fromEntries(files.map(file => [file,digest(source(file))]));
    const sql = migrations.map(source).join('\n');
    const fingerprint = source('fingerprint.sql').trim();
    const hash = digest(sql);
    return { hashes, sql, fingerprint, hash };
}

// 显式刷新发布清单和原生验证常量，正常迁移只读这两份文件。
function generate() {
    const { hashes, fingerprint, hash } = describe();
    fs.writeFileSync(path.join(__dirname,'manifest.json'),JSON.stringify(hashes,null,2)+'\n');
    const header = '#pragma once\n\n// Generated by schema/postgresql/contract.js from the checked SQL files.\n' +
        'namespace chat_pg {\ninline constexpr const char* SCHEMA_HASH = "' + hash + '";\n' +
        'inline constexpr const char* FINGERPRINT_SQL =\n    R"SQL(' + fingerprint + ')SQL";\n}\n';
    fs.writeFileSync(path.join(__dirname,'SchemaVersion.h'),header);
}

if (require.main === module) generate();
module.exports = { source, describe };
