CREATE TABLE apply_friend (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_uid bigint NOT NULL, to_uid bigint NOT NULL, status integer NOT NULL DEFAULT 0,
    description bytea NOT NULL, backname bytea NOT NULL,
    revision bigint NOT NULL DEFAULT 1, UNIQUE (from_uid, to_uid)
);
CREATE TABLE friend (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
