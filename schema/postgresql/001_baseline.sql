CREATE TABLE account (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uid bigint NOT NULL UNIQUE,
    name bytea NOT NULL, email bytea NOT NULL,
    name_key bytea NOT NULL UNIQUE, email_key bytea NOT NULL UNIQUE,
