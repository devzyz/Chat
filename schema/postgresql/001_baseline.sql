);
CREATE TABLE chat (
    chat_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type text NOT NULL CHECK (type IN ('private','group')),
    created_at timestamptz NOT NULL DEFAULT date_trunc('second', statement_timestamp())
);
CREATE TABLE private_chat (
    chat_id bigint PRIMARY KEY, user1_id bigint NOT NULL, user2_id bigint NOT NULL,
    created_at timestamptz NOT NULL DEFAULT date_trunc('second', statement_timestamp()),
    relationship_active boolean NOT NULL DEFAULT true,
    relationship_revision bigint NOT NULL DEFAULT 1, UNIQUE (user1_id, user2_id)
);
CREATE INDEX private_first ON private_chat (user1_id, chat_id);
CREATE INDEX private_second ON private_chat (user2_id, chat_id);
CREATE TABLE chat_message (
    message_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_id bigint NOT NULL, send_id bigint NOT NULL, recv_id bigint NOT NULL,
    content bytea NOT NULL, status smallint NOT NULL,
    created_at timestamptz NOT NULL DEFAULT date_trunc('second', statement_timestamp()),
    updated_at timestamptz NOT NULL DEFAULT date_trunc('second', statement_timestamp()),
    client_msg_uuid varchar(36) COLLATE "C",
    UNIQUE (send_id, client_msg_uuid), UNIQUE (chat_id, message_id)
);
CREATE INDEX message_time ON chat_message (chat_id, created_at);

CREATE TABLE group_chat (
    chat_id bigint PRIMARY KEY, name bytea, owner_uid integer,
    creator_uid integer, creation_uuid varchar(36) COLLATE "C", original_name bytea,
    dissolved boolean NOT NULL DEFAULT false, revision bigint NOT NULL DEFAULT 1,
    created_at timestamptz NOT NULL DEFAULT date_trunc('second', statement_timestamp()),
    UNIQUE (creator_uid, creation_uuid)
);
CREATE TABLE group_chat_member (
    chat_id bigint NOT NULL, user_id bigint NOT NULL, role smallint NOT NULL DEFAULT 0,
    joined_at timestamptz NOT NULL DEFAULT date_trunc('second', statement_timestamp()),
    state varchar(16) NOT NULL DEFAULT 'active', membership_epoch bigint NOT NULL DEFAULT 1,
    joined_after_id bigint NOT NULL DEFAULT 0, PRIMARY KEY (chat_id, user_id)
);
CREATE INDEX member_chats ON group_chat_member (user_id, chat_id);
CREATE TABLE group_creation_member (
    chat_id bigint NOT NULL, user_id bigint NOT NULL, PRIMARY KEY (chat_id, user_id)
);
CREATE TABLE group_operation (
    actor_uid integer NOT NULL, request_id varchar(36) COLLATE "C" NOT NULL,
    chat_id bigint NOT NULL, payload text NOT NULL, result text NOT NULL, PRIMARY KEY (actor_uid, request_id)
);
CREATE TABLE private_chat_receipt_clock (chat_id integer PRIMARY KEY, last_revision bigint NOT NULL DEFAULT 0);
CREATE TABLE chat_message_receipt (
    chat_id integer NOT NULL, message_id integer NOT NULL, recipient_uid integer NOT NULL,
    level smallint NOT NULL CHECK (level IN (1,2)), delivered_at bigint NOT NULL, read_at bigint,
    revision bigint NOT NULL CHECK (revision > 0), PRIMARY KEY (chat_id, message_id, recipient_uid),
    UNIQUE (chat_id, revision), CHECK ((level=1 AND read_at IS NULL) OR (level=2 AND read_at IS NOT NULL))
);
CREATE TABLE resource_file (
    resource_id varchar(36) COLLATE "C" PRIMARY KEY, owner_uid bigint NOT NULL,
    name bytea NOT NULL, media_type varchar(64) NOT NULL,
    size_bytes bigint NOT NULL CHECK (size_bytes >= 0), sha256 char(64) COLLATE "C" NOT NULL,
    created_at timestamptz NOT NULL DEFAULT date_trunc('second', statement_timestamp())
);
CREATE TABLE resource_message (
    message_id bigint PRIMARY KEY, resource_id varchar(36) COLLATE "C" NOT NULL,
    sender_uid bigint NOT NULL, client_uuid varchar(64) COLLATE "C" NOT NULL, UNIQUE (sender_uid, client_uuid)
);
CREATE INDEX resource_reference ON resource_message (resource_id);
CREATE TABLE user_avatar (
    uid bigint PRIMARY KEY, resource_id varchar(36) COLLATE "C" NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT date_trunc('second', statement_timestamp())
);
CREATE INDEX avatar_resource ON user_avatar (resource_id);
